/** The explanation for one flag note, or null when the note is information only. */
export const explainFlag = (text) => FLAG_EXPLAIN.find(f => f.test.test(String(text || ''))) || null;

/** One line for a tooltip / Excel: "เกิดอะไร — ทำไม · ต้องทำ: 1) … 2) …" */
export const explainOneLine = (e) => (e ? `${e.what} — ${e.why} · ต้องทำ: ${e.todo.map((t, i) => `${i + 1}) ${t}`).join(' ')}` : '');

/** The steps for one audit row (status first, then each recognised flag, no repeats); [] for a clean "ตรง". */
export function todoForRow(r) {
    const out = [];
    const add = (e) => { for (const t of e?.todo || []) if (!out.includes(t)) out.push(t); };
    if (r?.status && r.status !== 'ok') add(STATUS_EXPLAIN[r.status]);
    if (r?.downStatus && r.downStatus !== 'ok') add(DOWN_EXPLAIN[r.downStatus]);
    for (const f of [r?.reason, ...(r?.flags || [])]) add(explainFlag(f));
    return out;
}
